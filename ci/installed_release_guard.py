"""Fail closed unless the imported runtime is the exact installed release wheel.

This is an acceptance helper, not an installer. It never edits sys.path, installs
anything or contacts the network. A source checkout is deliberately insufficient.
"""
from __future__ import annotations

import base64
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import re

STAGE_A = {
    "version": "0.2.34",
    "commit": "0c990137e3b713f944cd7a053f04d0e8470af337",
    "coreRevision": "8c65fc7311062169d1b1e058c5463a39efaed3d9",
}


def validate_lock(lock):
    if not isinstance(lock, dict) or any(lock.get(key) != value for key, value in STAGE_A.items()):
        raise ValueError("STAGE_A_RELEASE_LOCK_NOT_READY")
    expected = ("https://github.com/levencode-labs/deploom-mcp/releases/download/"
                "v0.2.34/deploom_mcp-0.2.34-py3-none-any.whl")
    if (lock.get("repository") != "levencode-labs/deploom-mcp"
            or lock.get("tag") != "v0.2.34" or lock.get("url") != expected
            or not re.fullmatch(r"[0-9a-f]{64}", str(lock.get("sha256", "")))):
        raise ValueError("STAGE_A_RELEASE_LOCK_INVALID")
    return lock


def verify_direct_url(direct, lock):
    if not isinstance(direct, dict) or direct.get("url") != lock["url"] or "dir_info" in direct:
        raise ValueError("PUBLISHED_WHEEL_INSTALL_REQUIRED")
    archive = direct.get("archive_info", {})
    if not isinstance(archive, dict):
        raise ValueError("INSTALLED_WHEEL_ORIGIN_HASH_MISMATCH")
    hashes = archive.get("hashes", {})
    if (not isinstance(hashes, dict)
            or ("sha256" in hashes and hashes["sha256"] != lock["sha256"])
            or ("hash" in archive and archive["hash"] != "sha256=" + lock["sha256"])
            or not (hashes.get("sha256") == lock["sha256"]
                    or archive.get("hash") == "sha256=" + lock["sha256"])):
        raise ValueError("INSTALLED_WHEEL_ORIGIN_HASH_MISMATCH")


def check_installed(lock_file):
    lock = validate_lock(json.loads(Path(lock_file).read_bytes()))
    if os.environ.get("PYTHONPATH"):
        raise ValueError("PYTHONPATH_FORBIDDEN_IN_INSTALLED_RELEASE_GATE")
    import deploom_mcp
    from deploom_mcp.distribution import resolve_core_dir, release_manifest_path
    distribution = importlib.metadata.distribution("deploom-mcp")
    package = Path(deploom_mcp.__file__).resolve().parent
    installed = Path(distribution.locate_file("deploom_mcp")).resolve()
    if package != installed or package.parent.name not in {"site-packages", "dist-packages"}:
        raise ValueError("IMPORTED_RUNTIME_IS_NOT_INSTALLED_DISTRIBUTION")
    if distribution.version != lock["version"] or deploom_mcp.__version__ != lock["version"]:
        raise ValueError("INSTALLED_MCP_VERSION_MISMATCH")
    direct = distribution.read_text("direct_url.json")
    if not direct:
        raise ValueError("INSTALLED_WHEEL_ORIGIN_MISSING")
    verify_direct_url(json.loads(direct), lock)
    files = list(distribution.files or [])
    if not files:
        raise ValueError("INSTALLED_WHEEL_RECORD_MISSING")
    verified = 0
    for entry in files:
        # The entry-point launchers are generated by pip; validate all original
        # package and metadata payloads with their installed wheel RECORD.
        if not str(entry).startswith(("deploom_mcp/", "deploom_mcp-")) or entry.hash is None:
            continue
        target = Path(distribution.locate_file(entry)).resolve()
        if not target.is_relative_to(package.parent) or entry.hash.mode != "sha256":
            raise ValueError("INSTALLED_WHEEL_RECORD_INVALID")
        raw = target.read_bytes()
        actual = base64.urlsafe_b64encode(hashlib.sha256(raw).digest()).decode().rstrip("=")
        if actual != entry.hash.value or (entry.size is not None and len(raw) != entry.size):
            raise ValueError("INSTALLED_WHEEL_PAYLOAD_CHANGED")
        verified += 1
    if verified == 0:
        raise ValueError("INSTALLED_WHEEL_RECORD_EMPTY")
    core = resolve_core_dir().resolve()
    manifest_path = release_manifest_path().resolve()
    if core != package / "_core" or manifest_path != package / "resources/release-manifest.json":
        raise ValueError("BUNDLED_INSTALLED_CORE_REQUIRED")
    manifest = json.loads(manifest_path.read_bytes())
    if manifest.get("mcpVersion") != lock["version"] or manifest.get("core", {}).get("revision") != lock["coreRevision"]:
        raise ValueError("INSTALLED_CORE_PIN_MISMATCH")
    files = manifest["core"].get("files")
    if (not isinstance(files, dict) or not {"VERSION", "dependency_live_roadmap_generator.py"} <= set(files)
            or len(files) > 4096):
        raise ValueError("INSTALLED_CORE_INVENTORY_INVALID")
    inventory = json.dumps(files, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()
    if hashlib.sha256(inventory).hexdigest() != manifest["core"].get("contentSha256"):
        raise ValueError("INSTALLED_CORE_INVENTORY_INVALID")
    for name, expected in files.items():
        target = (core / name).resolve()
        if not target.is_relative_to(core) or hashlib.sha256(target.read_bytes()).hexdigest() != expected:
            raise ValueError("INSTALLED_CORE_PAYLOAD_CHANGED")
    return {
        "status": "EXACT_PUBLISHED_WHEEL_INSTALLED", "mcpVersion": distribution.version,
        "mcpCommit": lock["commit"], "coreRevision": lock["coreRevision"],
        "wheelUrl": lock["url"], "wheelSha256": lock["sha256"],
        "installedRecordFilesVerified": verified,
        "coreFilesVerified": len(files),
        "runtimeOrigin": "installed-published-wheel", "sourceImportsAllowed": False,
    }
